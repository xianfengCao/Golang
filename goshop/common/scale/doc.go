// Package scale 是按「集群目标 10 亿并发」写的进程内基础件。
//
// 聊天、商城、代驾各有一份相同的代码。三份不能合成一个模块：它们的 go.mod 互相独立，
// 学习时也可以只启动其中一个项目。
//
// 先把目标说清楚，避免把「10 亿并发」理解成「一个进程里开 10 亿条数据库连接」：
//
//   - 10 亿是整个集群同时在处理的请求规模，不是单机连接数。
//   - 单进程只负责一个分片上的一部分用户。用户落到哪台机器，用一致性哈希决定。
//   - 数据库连接是稀缺资源。单库通常只能承受几千条连接，所以要分库，并且每个进程的池子有硬上限。
//   - 请求路径上不做事的副作用（写历史、发通知、派单）丢进有界队列，由固定数量的工人消费。
//     队列满了就拒绝新任务，而不是把内存撑爆。这叫背压。
//   - 同一条数据的并发修改要么交给数据库的一条原子 SQL，要么用分片锁，不能靠一把全局大锁。
//   - 打到外部接口的相同请求要合并（singleflight），失败要熔断，否则一个慢下游会拖死所有工人。
//
// 本包只用标准库，方便 Go 1.17 的模块直接编译。真正上线时，队列应换成按 Key 分区的
// Kafka 或 Pulsar，锁应换成 Redis 或数据库行锁，但调用方式和这里的语义保持一致：
// 同 Key 有序、容量有界、失败可拒绝、连接可归还。
